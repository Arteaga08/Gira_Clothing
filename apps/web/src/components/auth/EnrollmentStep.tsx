"use client";

import type { EnrollmentStartResponse, Wire } from "@gira/shared";
import { type FormEvent, useEffect, useState } from "react";
import { Button } from "@/components/ui/Button";
import { Field } from "@/components/ui/Field";
import { Notice } from "@/components/ui/Notice";
import { isApiError } from "@/lib/api/ApiError";
import { completeEnrollment, startEnrollment } from "@/lib/api/auth";

interface EnrollmentStepProps {
  /** The factor is on and the session is open: the parent navigates. */
  onDone: () => void;
  /** The 5-minute challenge is gone (401): the parent sends the admin back to the password step. */
  onExpired: (message: string) => void;
}

const describe = (error: unknown): { message: string; status: number } =>
  isApiError(error)
    ? { message: error.message, status: error.status }
    : { message: "Ocurrió un error inesperado.", status: 0 };

/**
 * Forced enrolment of the admin's second factor. The key is generated by the
 * API when this mounts (`enroll/start`) and only becomes active once the first
 * code is confirmed (`enroll/complete`), which also opens the session.
 */
const EnrollmentStep = ({ onDone, onExpired }: EnrollmentStepProps) => {
  const [setup, setSetup] = useState<Wire<EnrollmentStartResponse> | null>(null);
  const [code, setCode] = useState("");
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    // Strict Mode mounts twice in development. The server returns the same
    // pending key for repeated starts, so both answers agree; `cancelled` just
    // keeps the unmounted run from setting state.
    let cancelled = false;
    startEnrollment()
      .then((started) => {
        if (!cancelled) setSetup(started);
      })
      .catch((caught: unknown) => {
        if (cancelled) return;
        const { message, status } = describe(caught);
        if (status === 401) onExpired(message);
        else setError(message);
      });
    return () => {
      cancelled = true;
    };
    // onExpired is a fresh closure each render of the parent; the request must
    // run once per mount.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const handleSubmit = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    if (pending) return;
    setPending(true);
    setError(null);
    try {
      await completeEnrollment(code);
      onDone();
    } catch (caught) {
      const { message, status } = describe(caught);
      setPending(false);
      if (status === 401) onExpired(message);
      else setError(message);
    }
  };

  return (
    <div className="flex flex-col gap-4">
      <Notice variant="info" title="Activa la verificación en dos pasos">
        Es obligatoria para entrar al panel. Tienes 5 minutos para completar este paso.
      </Notice>
      <ol className="list-decimal space-y-1 pl-5 text-sm leading-relaxed">
        <li>Abre tu app de autenticación (Google Authenticator, Authy, 1Password…).</li>
        <li>Escanea el código QR o escribe la clave manualmente.</li>
        <li>Ingresa el código de 6 dígitos que muestre la app.</li>
      </ol>

      {setup ? (
        <div className="flex flex-col items-center gap-2">
          {/* eslint-disable-next-line @next/next/no-img-element -- a data: URL: next/image has nothing to optimise */}
          <img
            src={setup.qrDataUrl}
            alt="Código QR para tu app de autenticación"
            width={240}
            height={240}
            className="rounded-nb-sm border-2 border-ink bg-white"
          />
          <p className="text-2xs text-text-muted">¿No puedes escanear? Escribe esta clave:</p>
          <code className="break-all rounded-nb-sm border-2 border-ink bg-surface px-2 py-1 font-mono text-sm font-bold">
            {setup.manualKey}
          </code>
        </div>
      ) : error ? null : (
        <p aria-live="polite" className="text-sm text-text-muted">
          Preparando tu código QR…
        </p>
      )}

      {setup ? (
        <form onSubmit={(event) => void handleSubmit(event)} noValidate className="flex flex-col gap-4">
          <Field
            label="Código de verificación"
            inputMode="numeric"
            autoComplete="one-time-code"
            maxLength={6}
            pattern="\d{6}"
            required
            // The form only mounts once the QR is ready, so this moves focus
            // to the next thing to do rather than stealing it on load.
            autoFocus
            value={code}
            onChange={(event) => setCode(event.target.value)}
          />
          {error ? (
            <Notice variant="danger" title="Error">
              {error}
            </Notice>
          ) : null}
          <Button type="submit" variant="primary" loading={pending}>
            Activar y entrar
          </Button>
        </form>
      ) : error ? (
        <Notice variant="danger" title="Error">
          {error}
        </Notice>
      ) : null}
    </div>
  );
};

export { EnrollmentStep };
